/* くまの記録 — 画像の設定ファイル(もとの設定)
 *
 * いちばん簡単なのは、記録する人の画面の「くま」タブから画像を登録して選ぶ方法です(GitHub への上げ直し不要)。
 * サイトで選んだものがある場面は、そちらが優先されます。このファイルは、サイトで何も選んでいない時の設定です。
 *
 * このファイルと同じフォルダ(docs/images/)に画像ファイルを置き、ここで名前を付けて登録します。
 * 画面のどこにどの画像を出すか(スロット)と、リアクションの種類もここで決めます。
 * くわしい手順と画像の作り方は、プロジェクト直下の IMAGES.md を見てください。
 *
 * 書き方のルール
 *   - 文字は ' ' (半角の引用符)で囲む。行の終わりはカンマ。最後の行はカンマなしでもよい。
 *   - 画像ファイル名は大文字小文字を区別する(kuma-happy.png と Kuma-Happy.png は別物)。
 *   - 間違えて壊してしまった場合、画面は内蔵のくま(絵文字とSVG)に戻るだけで、記録は消えません。
 *     サポーター画面の「設定」タブの下に「画像とリアクション」の一覧が出るので、そこで確認できます。
 */
window.KUMA_IMAGES = {

  /* ---------------------------------------------------------------
   * 1. 画像の登録(ライブラリ)
   *    「名前: 'ファイル名'」の形で、使いたい画像を全部ここに書く。
   *    名前は半角英数字と _ だけ。ファイルは docs/images/ に置く(png / jpg / webp / gif / svg)。
   *    おすすめ: 正方形、背景が透明の PNG、400〜1024 ピクセル、1ファイル 300KB 以下。
   * --------------------------------------------------------------- */
  library: {
    kuma_normal: 'kuma-normal.svg',   // ふつうの顔
    kuma_happy:  'kuma-happy.svg',    // うれしい(目を閉じて笑う)
    kuma_sleepy: 'kuma-sleepy.svg',   // ねむい(朝 10 時前)
    kuma_love:   'kuma-love.svg',     // ハート目(ひとことが届いた時)
    kuma_cheer:  'kuma-cheer.svg',    // 大よろこび(今の版では使っていない)
    kuma_crown:  'kuma-crown.svg'     // 王冠(今の版では使っていない)
    // 例: 自分で作った画像を足すときは、ファイルを置いてから1行足す
    // kuma_hachimitsu: 'hachimitsu.png',
  },

  /* ---------------------------------------------------------------
   * 2. 画面のどこに、どの画像を出すか(スロット)
   *    値には「ライブラリの名前」を書く。'' (空)にすると内蔵のくまに戻る。
   *    [ 'kuma_normal', 'kuma_hachimitsu' ] のように [ ] で複数書くと、日替わりで変わる。
   * --------------------------------------------------------------- */
  slots: {
    title:      'kuma_normal',   // ログイン画面のタイトルの大きなくま
    loading:    'kuma_normal',   // 読み込み中
    normal:     'kuma_normal',   // 本人の画面のくま(ふだん)
    happy:      'kuma_happy',    // 本人の画面のくま(「ありがとう」の後・なでた時)
    sleepy:     'kuma_sleepy',   // 本人の画面のくま(朝 10 時前)
    love:       'kuma_love',     // 本人の画面のくま(ひとことが届いている時)
    role_patient:   '🐻',        // ログイン画面「本人」ボタンの絵。絵文字でも、ライブラリの名前でもよい
    role_supporter: '🧸'         // ログイン画面「記録する人」ボタンの絵
  },

  /* ---------------------------------------------------------------
   * 3. ひとことの種類(記録する人が本人に送れるもの)。サイトの「くま」タブで変えると、そちらが優先される
   *    1 行が 1 種類。上から順にボタンが並ぶ。増やすときは { } のかたまりを 1 つ足す。
   *      id:    半角英数字と _ - だけ。他と重ならないように。記録(スプレッドシート)にはこの id が残る
   *      label: ボタンの下と、本人のふきだしに出る短い言葉
   *      image: 絵文字 1 つ、またはライブラリの名前
   * --------------------------------------------------------------- */
  reactions: [
    { id: 'heart', label: '見たよ',   image: '❤️' },
    { id: 'clap',  label: 'えらい',   image: '👏' },
    { id: 'honey', label: 'おつかれ', image: '🍯' },
    { id: 'bear',  label: 'だいすき', image: 'kuma_love' }
    // 例: { id: 'ganbare', label: 'がんばれ', image: 'kuma_hachimitsu' },
  ]
};
